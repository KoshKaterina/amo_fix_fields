#!/bin/sh
# Шаг F. Выгрузка строк журнала по событиям Sipuni для разбора тестовых звонков (только чтение).
# Запуск на сервере: sudo sh server_events_tail.sh [сколько_минут_назад]   (по умолчанию 120)
# Номера клиентов в выводе маскируются (все цифры, кроме двух последних, если их 7 и больше).
MIN="${1:-120}"
docker logs --since "${MIN}m" amo-fix-fields 2>&1 \
  | grep -E 'Sipuni' \
  | sed -E 's/[0-9]{7,}/<цифры>/g' \
  | cut -c1-260

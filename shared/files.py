"""Атомарная запись json - одна реализация вместо семнадцати.

Замер 07.10.2026: `os.replace` поверх временного файла встречается в **15 файлах, 17 мест**,
и образец всюду дословно одинаковый:

    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f)
    os.replace(tmp, path)

Поэтому здесь это не «улучшение», а ровно то же поведение в одном месте.

⚠️ ОДНО ОТЛИЧИЕ ОТ КОПИЙ, И ОНО НАМЕРЕННОЕ: добавлен `fsync`. Ни одна из 15 копий его не
делает (проверено). `os.replace` обещает, что подмена имени произойдёт целиком - но НЕ
обещает, что данные уже на диске. При жёсткой перезагрузке можно получить пустой или
обрезанный файл с правильным именем, и для множеств «кому уже слали алерт» это значит
повторную рассылку людям. Цена - один вызов на запись файла в десятки килобайт.

⚠️ Временный файл кладётся РЯДОМ с целевым, а не в /tmp. `os.replace` атомарен только внутри
одной файловой системы; через границу он превращается в копирование, и атомарность теряется.

⚠️ `ensure_ascii` по умолчанию True - как в существующих копиях (`json.dump(data, f)`).
Русский текст в таких файлах уедет экранированным; это некрасиво, но менять по умолчанию
нельзя: старые файлы читаются и перезаписываются тем же кодом, и разница в кодировании
породила бы бессмысленные расхождения при сверке.
"""
from __future__ import annotations

import json
import os
from typing import Any


def write_json_atomic(path: str, data: Any, *, ensure_ascii: bool = True) -> None:
    """Записать json так, чтобы читатель никогда не увидел недописанный файл.

    Каталог создаётся, если его нет. Исключения НЕ глотаются: вызывающий сам решает, что
    делать с отказом записи - большинство существующих мест пишет `logger.exception` и живёт
    дальше, и это их право, а не правило на всех.
    """
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(data, handle, ensure_ascii=ensure_ascii)
        handle.flush()
        os.fsync(handle.fileno())        # см. шапку: иначе имя подменится, а данных не будет
    os.replace(tmp, path)


def read_json(path: str, default: Any = None) -> Any:
    """Прочитать json; файла нет или он битый - вернуть `default`.

    Битый файл - не исключение, а штатный случай: это состояние «что уже сделали», и если
    оно потерялось, правильное поведение - начать с чистого листа, а не упасть на старте.
    """
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return default

"""Телефон: только ПРИМИТИВЫ. Общей «нормализации» здесь нет, и это главное про этот модуль.

⚠️ ЧИТАТЬ ПЕРЕД ТЕМ, КАК ИСКАТЬ ЗДЕСЬ `normalize_phone`.

Замер 07.10.2026 нашёл шесть своих функций по телефону в шести файлах. Выглядит как дубль, но
**они не взаимозаменяемы** - каждая отвечает на свой вопрос и возвращает своё:

| где | что делает | что отдаёт |
|---|---|---|
| `site_form_service._normalize_phone` | цифры, 11 цифр с 8 -> 7 | `+<цифры>` |
| `site_form_service.normalize_phone_v2` | то же плюс СТРОГАЯ проверка: мусор отвергается | `+7…` либо `""` |
| `site_form_service._fallback_phone` | ищет телефон по всем полям формы | первый подходящий |
| `amgroup_lead_builder._normalize_phone_digits` | цифры, 11 цифр с 8 -> 7 | **цифры без `+`** |
| `jivo_service._normalize_phone` | приводит формат Jivo к виду с `+` | `+<цифры>` |
| `waybill_config.country_code_from_phone` | определяет СТРАНУ по префиксу | код страны, по умолчанию `RU` |

Свести их в одну функцию - это не убрать дублирование, а **поменять поведение** сразу в
нескольких боевых путях: где-то ждут цифры без плюса, где-то пустую строку на мусоре, где-то
страну. Такой заход делается отдельно, по одному вызывающему, с проверкой на живых данных -
и это не задача «вынести общее».

**Поэтому здесь лежит только то, что во всех вариантах одинаково** - два шага внутри. Новый
код собирает из них нужное ему поведение и явно пишет, какое именно. Старые функции остаются
на месте.
"""
from __future__ import annotations

import re

_NON_DIGITS = re.compile(r"\D")


def digits_only(raw: str | None) -> str:
    """Оставить от строки только цифры. Пусто на входе - пусто на выходе."""
    return _NON_DIGITS.sub("", raw or "")


def ru_8_to_7(digits: str) -> str:
    """Российский номер из 11 цифр, начинающийся на 8, привести к виду с 7.

    Только это и только для одиннадцати цифр: так делают все существующие варианты. Строку
    другой длины НЕ трогаем - у международных номеров ведущая восьмёрка значит другое
    (например 86 это Китай), и «починка» испортила бы номер.
    """
    if len(digits) == 11 and digits.startswith("8"):
        return "7" + digits[1:]
    return digits

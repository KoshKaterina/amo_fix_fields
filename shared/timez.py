"""Московское время - одно объявление на весь сервис.

Замер 07.10.2026: с московским временем работают 20 файлов, и общего места не было ни у
одного. Из них **18 вшивали `datetime.timedelta(hours=3)` прямо по месту**, 3 объявляли своё
`MSK`, 2 брали `ZoneInfo("Europe/Moscow")`. Опасность не теоретическая: когда такую константу
однажды поправят, поправят её в одном файле из двадцати, а остальные девятнадцать останутся
прежними - и расхождение будет видно не в логе, а в чужом отчёте.

⚠️ ПОЧЕМУ ФИКСИРОВАННЫЙ СДВИГ, А НЕ `ZoneInfo`. Москва живёт на UTC+3 постоянно с 26.10.2014,
перехода на летнее время нет. Для любой даты после этого дня `timezone(timedelta(hours=3))` и
`ZoneInfo("Europe/Moscow")` дают один и тот же результат - то есть два существующих файла с
`ZoneInfo` можно перевести сюда, ничего не изменив. А фиксированный сдвиг вдобавок не зависит
от наличия базы часовых поясов в образе, то есть не ломается от сборки без `tzdata`.

⚠️ Если однажды понадобятся даты РАНЬШЕ 26.10.2014 (исторические выгрузки), фиксированный
сдвиг для них неверен: тогда в Москве было UTC+4 и действовало летнее время. Такой случай
требует отдельной функции и отдельного разговора, молча менять этот модуль нельзя.
"""
from __future__ import annotations

import datetime as dt

#: Московское время. Единственное объявление; не копировать по месту.
MSK = dt.timezone(dt.timedelta(hours=3))


def now_msk() -> dt.datetime:
    """Текущее время в Москве, с часовым поясом (aware)."""
    return dt.datetime.now(MSK)


def to_msk(moment: dt.datetime) -> dt.datetime:
    """Перевести момент в московское время.

    Наивное время (без пояса) считаем временем в UTC - так ведёт себя `datetime.timestamp()`
    и так приезжают метки от amoCRM. Если наивное значение на самом деле местное, переводить
    его этой функцией НЕЛЬЗЯ: сперва припишите ему правильный пояс.
    """
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=dt.timezone.utc)
    return moment.astimezone(MSK)


def msk_date(moment: dt.datetime | None = None) -> dt.date:
    """Календарный день по московскому времени - то, что люди называют «датой»."""
    return to_msk(moment or dt.datetime.now(dt.timezone.utc)).date()

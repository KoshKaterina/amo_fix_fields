"""Фильтр «сообщение не требует ответа» — не запускаем SLA-таймер на закрывашках.

Идея Кати (03.08.2026): половина SLA-алертов приходит на сообщения, отвечать на
которые не нужно вовсе — клиент прислал реакцию, поблагодарил или подтвердил уже
сказанное. ИИ тут не нужен: сценарии типовые и ловятся правилами.

Список собран НЕ из головы, а из живого корпуса `wazzup_message` панели (992
сообщения, 474 входящих, 30.06–03.08.2026): на момент замера 49 чатов висели без
ответа >15 мин, из них 20 (41%) — закрывашки.

ГЛАВНЫЙ ПРИНЦИП (правка Кати на разборе корпуса): глушим только то, что ЗАКРЫВАЕТ
разговор. Всё, что сообщает НОВЫЙ ФАКТ или требует действия, — алертим, даже если
оно короткое:
  «Подъехал», «На месте»       — клиент у дверей, надо бежать (пример Кати)
  «Оплачено»                    — надо проверить платёж (по корпусу — ответ на
                                  «Благодарим за заказ, передаём в комплектацию»)
  «Буду через 25-30»            — договорённость по времени
  «Лучше верните деньги»        — конфликт
  «Здравствуйте», «Добрый день» — ОТКРЫВАШКА, разговор только начинается
  «Да», «1»                     — выбор в диалоге, за ним ждут продолжения

Почему вайтлист именно такой: «Да, всё верно» (16 раз) и «Нет, благодарю» (8) —
это ответы на кнопки НАШИХ ботов («Вы оформили заказ №…, всё верно?», «Нужна
помощь?»), проверено джойном с предыдущим исходящим по корпусу.

РАЗБОР ПО СЛОВАМ (06.08.2026, вторая правка по корпусу за 28.07–06.08). Точное
совпадение фразы ловило мало: до менеджеров за 9 дней долетело 180 алертов, и
каждый седьмой был той же благодарностью, но с хвостом — «Ок, спасибо»,
«Спасибо. Понял», «Понял, благодарю», «супер спасибо». Плодить их в списке
бессмысленно, комбинаций бесконечно много. Поэтому сообщение режется на слова, и
глушим, только если КАЖДОЕ слово безобидное и есть хотя бы одно ЯДРОВОЕ:

  ядро (_CORE_TOKENS)     — слово само закрывает разговор: спасибо, ок, понял…
  хвост (_FILLER_TOKENS)  — рядом с ядром допустимо, но само по себе ничего не
                            значит: да, нет, большое, вам, хорошего, дня…

Требование ядра — защита от двух ловушек живого корпуса: одинокое «Да» (выбор в
диалоге, за ним ждут продолжения) и «Доброго дня» (это ПРИВЕТСТВИЕ, а не
прощание). Оба состоят только из хвостовых слов → ядра нет → алерт идёт.

Незнакомое слово = потенциальный новый факт, поэтому «Нет, нужно исправить» и
«Спасибо, написал» будят менеджера, хотя начинаются как закрывашки.

Фильтр НЕ снимает уже идущее ожидание — только не запускает новое (см.
wazzup_sla.handle_webhook). Клиент спросил и не получил ответа, а потом написал
«спасибо» — вопрос всё ещё висит, алерт нужен.
"""

import logging
import re
import unicodedata

logger = logging.getLogger("uvicorn")

# Типы сообщений Wazzup, которые сами по себе не несут вопроса.
#   unsupported — заглушка Wazzup на неподдерживаемый формат: реакции, стикеры,
#     видеокружки («Вам что-то прислали. Такой формат сообщений пока не
#     поддерживается»). Решение Кати 03.08.2026: глушим, это и есть «клиент
#     прислал реакцию».
#   deleted — клиент удалил своё сообщение, отвечать не на что (8 таких алертов
#     за 9 дней, почти все от телеграм-ботов обменников).
#   system — служебная запись мессенджера, не текст человека.
_SILENT_TYPES = {"unsupported", "deleted", "system"}

# Закрывашки целыми фразами: то, что не раскладывается по словам (см. ниже) или
# читается только целиком. Сравнение по нормализованному тексту (см. _normalize).
_CLOSING_PHRASES = {
    "и вам спасибо", "нашла благодарю", "нашел благодарю",
    "спасибо нужная вещь", "благодарю обязательно ознакомлюсь",
    # вежливый отказ от дальнейшей помощи (ответ на кнопку «Нужна помощь?»)
    "не нужно спасибо", "нет не нужно",
    # подтверждение уже сказанного (ответ на кнопку «Всё верно?»)
    "да все верно", "да всё верно", "да верно", "все верно", "всё верно",
    "да все правильно", "всё правильно", "все правильно",
    # согласие-закрывашка
    "се четко", "все четко", "всё чётко", "договорились",
    "хорошо жду заказ", "хорошо буду ждать", "жду заказ",
    "спасибо будем иметь ввиду", "спасибо будем иметь в виду",
}

# ЯДРО: слово само по себе закрывает разговор — благодарность или «принято».
# Без хотя бы одного такого слова сообщение НЕ глушим.
_CORE_TOKENS = {
    "спасибо", "спасибки", "спс", "благодарю", "благодарью", "благодарствую",
    "ок", "окей", "хорошо", "отлично", "супер", "класс", "здорово",
    "замечательно", "прекрасно", "понял", "поняла", "понятно", "принял",
    "приняла", "принято", "ясно", "ладно", "взаимно",
    "ok", "okay", "thanks",
}

# ХВОСТ: рядом с ядром допустимо, само по себе ничего не значит.
# ⚠️ Сюда НЕЛЬЗЯ класть слово, которое в одиночку требует ответа: «да» и
# «доброго дня» держатся тут именно потому, что без ядра они не глушатся.
_FILLER_TOKENS = {
    "и", "а", "ну", "вам", "вас", "тебе", "очень", "всё", "все", "тоже", "уже",
    "да", "нет", "не", "ещё", "еще", "раз", "то", "большое", "огромное",
    "пребольшое", "четко", "чётко", "пожалуйста", "хорошего", "доброго", "дня",
    "вечера", "выходных",
}

_ALLOWED_TOKENS = _CORE_TOKENS | _FILLER_TOKENS

# Больше слов — больше шанс, что внутри спрятан факт. Порог по корпусу: все
# закрывашки укладываются в 6 слов.
_MAX_CLOSING_WORDS = 6

# Устойчивые связки: сводим к одному ядровому слову ДО разбора по словам, иначе
# «не нужно» распалось бы на два хвостовых слова и осталось без ядра.
_CLOSING_UNITS = (
    "не нужно", "не надо", "не требуется",
    "все хорошо", "всё хорошо", "все ок", "всё ок", "все понятно", "всё понятно",
    "спасибо большое", "большое спасибо", "спасибо огромное",
)
_UNIT_REPLACEMENT = " ок "

# Символы, которые сами по себе ничего не спрашивают: эмодзи, знаки, пробелы.
# Сообщение только из них (клиент прислал «🤝» или «))») ответа не требует.
_EMOJI_RANGES = (
    (0x1F000, 0x1FAFF),  # эмодзи, символы, пиктограммы
    (0x2190, 0x2BFF),    # стрелки, геометрия, разное
    (0x2600, 0x27BF),    # символы и дингбаты
    (0xFE00, 0xFE0F),    # вариационные селекторы
    (0x1F1E6, 0x1F1FF),  # флаги
    (0x200D, 0x200D),    # zero-width joiner (составные эмодзи)
    (0x2764, 0x2764),    # ❤
)


def _is_emoji_char(ch: str) -> bool:
    code = ord(ch)
    return any(lo <= code <= hi for lo, hi in _EMOJI_RANGES)


def _normalize(text: str) -> str:
    """К нижнему регистру, без эмодзи, пунктуации и лишних пробелов: «И спасибо.» →
    «и спасибо», «Спасибо. 🤝» → «спасибо». Так ни пунктуация, ни прилепленный
    смайлик не ломают совпадение (за 9 дней из-за смайлика мимо фильтра прошли
    «Спасибо 🙏», «Понял. 🫡», «Спасибо. 🤝»)."""
    s = unicodedata.normalize("NFKC", str(text or "")).lower()
    s = "".join(ch for ch in s if not _is_emoji_char(ch))
    s = re.sub(r"[.,!;:()\"'«»…\-–—/\\]+", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def _is_symbols_only(text: str) -> bool:
    """True — в сообщении нет ни одной буквы/цифры (только эмодзи, скобки, знаки)."""
    s = str(text or "").strip()
    if not s:
        return False
    return not any(ch.isalnum() for ch in s)


def _is_bot_command(text: str) -> bool:
    """«/start» и подобное — команда телеграм-бота, а не человек. Клиенты так не
    пишут: в корпусе это тест-аккаунты и спам-боты."""
    s = " ".join(str(text or "").split())
    return s.startswith("/") and " " not in s


def _all_words_closing(norm: str) -> bool:
    """True — текст целиком собран из безобидных слов и содержит ядровое."""
    reduced = norm
    for unit in _CLOSING_UNITS:
        reduced = reduced.replace(unit, _UNIT_REPLACEMENT)
    words = reduced.split()
    if not words or len(words) > _MAX_CLOSING_WORDS:
        return False
    if not all(w in _ALLOWED_TOKENS for w in words):
        return False
    return any(w in _CORE_TOKENS for w in words)


def is_closing_message(msg: dict) -> tuple[bool, str]:
    """(не требует ответа?, причина) для входящего сообщения Wazzup.

    Причина — короткая метка для лога, чтобы потом можно было посчитать, какое
    правило сколько глушит, и поправить список по фактам, а не на ощупь."""
    if not isinstance(msg, dict):
        return False, ""

    msg_type = str(msg.get("type") or "").strip().lower()
    if msg_type in _SILENT_TYPES:
        return True, f"type={msg_type}"

    raw_text = msg.get("text")
    text_s = str(raw_text or "")

    # «?» — всегда сигнал: клиент спрашивает. Даже одиночное «?» (есть в корпусе)
    # это вопрос, а не закрывашка. «!» стоп-сигналом НЕ делаем: «Спасибо!» —
    # обычная благодарность.
    if "?" in text_s:
        return False, ""

    # Только символы: глушим ЛИШЬ когда есть эмодзи (реакция «🤝»). Чистая
    # пунктуация («...», «!!!») — непонятный сигнал, безопаснее разбудить.
    if _is_symbols_only(raw_text):
        if any(_is_emoji_char(ch) for ch in text_s.strip()):
            return True, "эмодзи"
        return False, ""

    if _is_bot_command(text_s):
        return True, "команда бота"

    norm = _normalize(raw_text)
    if not norm:
        return False, ""  # пустой текст у media — это НЕ закрывашка (фото/голосовое)
    if norm in _CLOSING_PHRASES:
        return True, f"закрывашка «{norm}»"
    if _all_words_closing(norm):
        return True, f"закрывашка «{norm}»"

    return False, ""

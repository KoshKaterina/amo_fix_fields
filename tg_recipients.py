#   • в чат ОП идёт СОБЫТИЕ, чтобы менеджер отработал его прямо сейчас, и там нужен @тег;
#   • в чат руководства идёт ПРОВАЛ — то, что уже не отработали, — и тег там не нужен:
#     менеджеров в группе нет, а руководителю важно имя человека, а не его ник.
